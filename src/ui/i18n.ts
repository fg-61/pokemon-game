export type StrKey = keyof (typeof STR)['en'];

function detect(): Lang {
  try {
    const saved = localStorage.getItem('pba.lang');
    if (saved === 'tr' || saved === 'en') return saved;
  } catch {
    /* ignore */
  }
  return navigator.language?.toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

let lang: Lang = detect();

export function getLang(): Lang {
  return lang;
}
export function setLang(l: Lang) {
  lang = l;
  try {
    localStorage.setItem('pba.lang', l);
  } catch {
    /* ignore */
  }
}

export function t(key: StrKey, ...args: (string | number)[]): string {
  let s: string = STR[lang][key] ?? STR.en[key];
  args.forEach((a, i) => (s = s.replace(`{${i}}`, String(a))));
  return s;
}

const STAT_TR: Record<string, string> = { Attack: 'Saldırısı', Defense: 'Savunması', 'Sp. Atk': 'Özel Saldırısı', 'Sp. Def': 'Özel Savunması', Speed: 'Hızı', accuracy: 'isabeti', evasiveness: 'kaçınması' };
export function statName(label: string): string {
  return lang === 'tr' ? (STAT_TR[label] ?? label) : label;
}
